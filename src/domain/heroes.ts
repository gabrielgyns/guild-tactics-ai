const HERO_BY_ID = new Map(HEROES.map((h) => [h.id, h]));

export function getHero(id: string): HeroDef {
  const hero = HERO_BY_ID.get(id);
  if (!hero) throw new Error(`Unknown hero: ${id}`);
  return hero;
}

export function basicAttack(hero: HeroDef): Ability {
  return {
    id: 'attack',
    name: 'Atacar',
    description: `Ataque básico${hero.attack.magic ? ' mágico' : ''}: 100% de dano (alcance ${hero.attack.min}–${hero.attack.max}).`,
    range: { min: hero.attack.min, max: hero.attack.max },
    target: 'enemy',
    area: { kind: 'single' },
    affects: 'enemies',
    cooldown: 0,
    effects: [{ kind: 'damage', power: 1, magic: hero.attack.magic }],
  };
}

export const DEFEND: Ability = {
  id: 'defend',
  name: 'Defender',
  description: 'Recebe −50% de dano até ao fim do próximo turno.',
  range: { min: 0, max: 0 },
  target: 'self',
  area: { kind: 'single' },
  affects: 'allies',
  cooldown: 0,
  effects: [{ kind: 'status', status: 'guard', duration: 1 }],
};

/** Full action list for a hero, in action-bar order. */
export function heroAbilities(hero: HeroDef): Ability[] {
  return [basicAttack(hero), ...hero.abilities, hero.ultimate, DEFEND];
}

export function findAbility(heroId: string, abilityId: string): Ability {
  const ability = heroAbilities(getHero(heroId)).find((a) => a.id === abilityId);
  if (!ability) throw new Error(`Unknown ability ${abilityId} for ${heroId}`);
  return ability;
}
