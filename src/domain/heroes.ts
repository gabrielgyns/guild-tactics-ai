const HERO_BY_ID = new Map(HEROES.map((h) => [h.id, h]));

export function getHero(id: string): HeroDef {
  const hero = HERO_BY_ID.get(id);
  if (!hero) throw new Error(`Unknown hero: ${id}`);
  return hero;
}

export function basicAttack(hero: HeroDef): Ability {
  return {
    id: 'attack',
    name: 'Atacar',
    description: `Ataque básico${hero.attack.magic ? ' mágico' : ''}: 100% de dano (alcance ${hero.attack.min}–${hero.attack.max}).`,
    range: { min: hero.attack.min, max: hero.attack.max },
    target: 'enemy',
    area: { kind: 'single' },
    affects: 'enemies',
    cooldown: 0,
    effects: [{ kind: 'damage', power: 1, magic: hero.attack.magic }],
  };
}

